export function registerTranslations(): void {
  Language.addTranslations('en', ENGLISH);
  Language.addTranslations('zh', SIMPLIFIED_CHINESE);
  Language.addTranslations('zh_tw', TRADITIONAL_CHINESE);
}

export function tr(key: string, variables?: Array<string | number>): string {
  const fullKey = key.startsWith('texture_model.') ? key : 'texture_model.' + key;
  return tl(fullKey, variables, ENGLISH[fullKey as keyof typeof ENGLISH] ?? fullKey);
}

export function errorMessage(error: unknown): string {
  if (error instanceof ModelValidationError) {
    const variables = error.translationVariables.length > 0
      ? error.translationVariables
      : error.translationKey === 'error.unexpected' ? [error.message] : undefined;
    return tr(error.translationKey, variables);
  }
  const detail = error instanceof Error ? error.message : String(error);
  return tr('error.unexpected', [detail]);
}
